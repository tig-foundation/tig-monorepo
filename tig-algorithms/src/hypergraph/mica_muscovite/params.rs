// Per-track settings.
//
// The 20k / 50k / 100k / 200k tracks share a single code path (`track.rs`); everything that
// separates them is a constant in the fields below, so a difference between tracks is
// visible here instead of hidden in duplicated code. The 10k track is separate
// (`track_10k.rs`) and carries three settings that exist nowhere else.

pub struct Piste {
    pub nom: &'static str,

    // Effort table: indexed 0..=5 by the `effort` hyperparameter, `effort_def` outside that
    // range. Tuple: (base_refine, base_ils, base_ils_quick, base_polish, base_post_balance).
    pub effort: [(usize, usize, usize, usize, usize); 6],
    pub effort_def: (usize, usize, usize, usize, usize),

    // Fuel ceiling: fixed cost plus per-round cost. At the recommended grant this never
    // binds; it caps the round count when the budget is small.
    pub fuel_fixed: u64,
    pub fuel_per_round: u64,

    // Hyperparameter defaults, i.e. what `{}` selects.
    pub swap_scale_def: u64,
    pub zgm_clamp: i64,
    pub zgm_def: i32,
    pub fm_rounds_def: usize,
    pub tabu_tenure_def: usize,
    pub move_limit_dense: usize,
    pub passes: usize,

    // Fixed constants, no hyperparameter.
    pub tabu_fail_tenure: usize,
    pub tabu_fail_mark_len: usize,
    pub extra_window: usize,

    // Kernel names. One PTX module holds all tracks, so each name carries a track suffix.
    pub k_cluster: &'static str,
    pub k_preferences: &'static str,
    pub k_assignments: &'static str,
    pub k_planted: &'static str,
    pub k_edge_flags: &'static str,
    pub k_moves: &'static str,
    pub k_moves_w8: &'static str,
    pub k_balance: &'static str,
    pub k_connectivity: &'static str,
    pub k_reduce_conn: &'static str,
    pub k_swap_gains: &'static str,
    pub k_choose_elite: &'static str,
    pub k_assign_elite: &'static str,
}

